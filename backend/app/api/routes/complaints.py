"""
Cyber Raksha AI - Cybercrime Complaint Assistant Routes
Assisted integration with the National Cyber Crime Reporting Portal (cybercrime.gov.in) & 1930 Helpline.
Generates structured legal-evidence drafts, tracks official acknowledgement numbers, and dispatches status updates.
"""
import secrets
from datetime import datetime, timezone
from typing import List, Optional
from fastapi import APIRouter, Depends, HTTPException, status, Request
from sqlalchemy.orm import Session

from app.database.session import get_db
from app.models.complaint import CybercrimeComplaint
from app.models.user import User
from app.schemas.complaint import (
    ComplaintDraftRequest,
    RecordAcknowledgementRequest,
    ComplaintStatusUpdateRequest,
    ComplaintResponse
)
from app.api.routes.auth import get_optional_current_user
from app.services.email_service import email_service

router = APIRouter(prefix="/complaints", tags=["Cybercrime Complaint Assistant"])


def _generate_complaint_id() -> str:
    random_hex = secrets.token_hex(4).upper()
    return f"CR-CMP-{datetime.now(timezone.utc).year}-{random_hex}"


def _get_tracking_instructions(complaint: CybercrimeComplaint) -> str:
    if complaint.status == "DRAFT" or not complaint.official_ack_number:
        return (
            "1. Review the generated complaint text and structured evidence.\n"
            "2. Visit the official portal https://cybercrime.gov.in or dial 1930 immediately.\n"
            "3. Select 'Report Cyber Crime' -> 'Report Financial Fraud' or 'Other Cyber Crime'.\n"
            "4. Copy-paste the structured summary and attach saved evidence screenshots.\n"
            "5. After receiving your official Acknowledgement / FIR reference number, return to Cyber Raksha and enter it under 'Record Ack Number'."
        )
    return (
        f"Citizen Acknowledgement Recorded: Tracked under Citizen-Entered Acknowledgement Number: {complaint.official_ack_number}. "
        "Official verification by cybercrime.gov.in portal authorities remains pending."
    )


def _to_response(complaint: CybercrimeComplaint) -> ComplaintResponse:
    return ComplaintResponse(
        complaint_id=complaint.complaint_id,
        user_id=complaint.user_id,
        device_id=complaint.device_id,
        complaint_category=complaint.complaint_category,
        suspect_identifier=complaint.suspect_identifier,
        financial_loss_inr=complaint.financial_loss_inr,
        description=complaint.description,
        evidence_summary=complaint.evidence_summary,
        official_portal_url=complaint.official_portal_url,
        helpline_number=complaint.helpline_number,
        status=complaint.status,
        verification_level=getattr(complaint, "verification_level", "USER_REPORTED_UNVERIFIED"),
        is_government_verified=getattr(complaint, "is_government_verified", False),
        official_ack_number=complaint.official_ack_number,
        official_submission_date=complaint.official_submission_date.isoformat() if complaint.official_submission_date else None,
        official_notes=complaint.official_notes,
        created_at=complaint.created_at.isoformat(),
        tracking_instructions=_get_tracking_instructions(complaint)
    )


@router.post("/draft", response_model=ComplaintResponse, status_code=status.HTTP_201_CREATED)
def create_complaint_draft(
    req: ComplaintDraftRequest,
    request: Request,
    db: Session = Depends(get_db)
):
    """
    Generates a structured, evidence-backed cybercrime complaint draft
    ready for submission to the National Cyber Crime Reporting Portal (cybercrime.gov.in) or Helpline 1930.
    """
    user = get_optional_current_user(request, db)
    complaint_id = _generate_complaint_id()
    now = datetime.now(timezone.utc)

    # Format structured evidence summary
    evidence_text = req.evidence_summary or (
        f"Suspect Target: {req.suspect_identifier or 'Unknown'}\n"
        f"Disclosed Financial Loss: INR {req.financial_loss_inr:,.2f}\n"
        f"Incident Category: {req.complaint_category}\n"
        f"Generated by Cyber Raksha AI Autonomous Defense Engine on {now.strftime('%Y-%m-%d %H:%M:%S UTC')}."
    )

    complaint = CybercrimeComplaint(
        complaint_id=complaint_id,
        user_id=user.id if user else None,
        device_id=req.device_id,
        incident_id=req.incident_id,
        complaint_category=req.complaint_category.upper(),
        suspect_identifier=req.suspect_identifier,
        financial_loss_inr=req.financial_loss_inr,
        description=req.description,
        evidence_summary=evidence_text,
        evidence_json=req.evidence_json,
        status="DRAFT",
        created_at=now,
        updated_at=now
    )
    db.add(complaint)
    db.commit()
    db.refresh(complaint)

    # Send confirmation email if user has email
    if user and user.email:
        email_service.send_complaint_confirmation_email(user.email, complaint_id, complaint.complaint_category)

    return _to_response(complaint)


@router.post("/{complaint_id}/ack", response_model=ComplaintResponse)
def record_official_acknowledgement(
    complaint_id: str,
    req: RecordAcknowledgementRequest,
    request: Request,
    db: Session = Depends(get_db)
):
    """
    Records the official citizen Acknowledgement Number received from
    cybercrime.gov.in or Helpline 1930 for ongoing case tracking.
    """
    complaint = db.query(CybercrimeComplaint).filter(CybercrimeComplaint.complaint_id == complaint_id).first()
    if not complaint:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Complaint record not found.")

    now = datetime.now(timezone.utc)
    complaint.official_ack_number = req.official_ack_number.strip()
    complaint.status = "OFFICIALLY_SUBMITTED"
    complaint.verification_level = "CITIZEN_PROVIDED_ACK"
    complaint.is_government_verified = False
    complaint.official_submission_date = now
    if req.notes:
        complaint.official_notes = (complaint.official_notes or "") + f"\n[{now.isoformat()}] {req.notes}"
    complaint.updated_at = now
    db.commit()
    db.refresh(complaint)

    # Dispatch email if user has email
    if complaint.user_id:
        user = db.query(User).filter(User.id == complaint.user_id).first()
        if user and user.email:
            email_service.send_complaint_confirmation_email(
                user.email, complaint.complaint_id, complaint.complaint_category, complaint.official_ack_number
            )

    return _to_response(complaint)


@router.get("", response_model=List[ComplaintResponse])
def list_complaints(
    request: Request,
    device_id: Optional[str] = None,
    db: Session = Depends(get_db)
):
    """Lists complaints associated with the authenticated user or device."""
    user = get_optional_current_user(request, db)
    query = db.query(CybercrimeComplaint)
    if user:
        query = query.filter(CybercrimeComplaint.user_id == user.id)
    elif device_id:
        query = query.filter(CybercrimeComplaint.device_id == device_id)
    else:
        # Return recent public anonymized or empty list
        return []

    complaints = query.order_by(CybercrimeComplaint.created_at.desc()).limit(50).all()
    return [_to_response(c) for c in complaints]


@router.get("/{complaint_id}", response_model=ComplaintResponse)
def get_complaint(
    complaint_id: str,
    db: Session = Depends(get_db)
):
    """Retrieves detailed status and structured evidence for a complaint."""
    complaint = db.query(CybercrimeComplaint).filter(CybercrimeComplaint.complaint_id == complaint_id).first()
    if not complaint:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Complaint record not found.")
    return _to_response(complaint)


@router.patch("/{complaint_id}/status", response_model=ComplaintResponse)
def update_complaint_status(
    complaint_id: str,
    req: ComplaintStatusUpdateRequest,
    db: Session = Depends(get_db)
):
    """Updates the status and notes for a complaint."""
    complaint = db.query(CybercrimeComplaint).filter(CybercrimeComplaint.complaint_id == complaint_id).first()
    if not complaint:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Complaint record not found.")

    valid_statuses = {"DRAFT", "AWAITING_SUBMISSION", "OFFICIALLY_SUBMITTED", "UNDER_REVIEW", "ACTION_TAKEN", "CLOSED"}
    new_st = req.status.upper().strip()
    if new_st not in valid_statuses:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail=f"Invalid status '{new_st}'. Must be one of {valid_statuses}."
        )

    now = datetime.now(timezone.utc)
    complaint.status = new_st
    if req.notes:
        complaint.official_notes = (complaint.official_notes or "") + f"\n[{now.isoformat()}] Status changed to {new_st}: {req.notes}"
    complaint.updated_at = now
    db.commit()
    db.refresh(complaint)

    if complaint.user_id:
        user = db.query(User).filter(User.id == complaint.user_id).first()
        if user and user.email:
            email_service.send_complaint_status_email(user.email, complaint.complaint_id, new_st, req.notes)

    return _to_response(complaint)

